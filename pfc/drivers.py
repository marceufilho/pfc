"""Reproducible standalone timing drivers; checksums are not differential oracles."""

from pfc import ir
from pfc.corpus import profile


def benchmark_driver(program: ir.Program) -> str:
    """Bounded inputs keep every executed operation defined, including repeated writes."""
    name = profile(program)
    function = program.functions[0]
    parameters = ", ".join(ir._declaration(p.symbol) for p in function.parameters)
    call = {
        "sum": "sum(a,n,n)",
        "dot": "dot(a,n,b,n,n)",
        "saxpy": "saxpy(2,a,n,b,n,n)",
        "prefix_sum": "prefix_sum(a,n,n)",
        "matvec": "matvec(a,n,b,n,c,n,rows,cols)",
        "binary_search": "binary_search(a,n,n,(iteration*104729)%n)",
    }[name]
    setup = "long cols=n<64?n:64; long rows=n/cols;" if name == "matvec" else ""
    initialization = "i" if name == "binary_search" else "1"
    reset = "for(long i=0;i<n;i++) a[i]=1;" if name == "prefix_sum" else ""
    tail = "c[rows-1]" if name == "matvec" else "c[n-1]"
    return f"""/* Generated by pfc.drivers.benchmark_driver. See docs/steps/15-six-kernels.md. */
#include <errno.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
{function.return_type} {name}({parameters});
static long positive(const char *text, long maximum) {{
 char *end; errno=0; long value=strtol(text,&end,10);
 return errno || *end || end==text || value<1 || value>maximum ? 0 : value;
}}
int main(int argc,char **argv) {{
 if(argc>3) return 2;
 long n=argc>1?positive(argv[1],16777216):16777216;
 long repeats=argc>2?positive(argv[2],50):50;
 if(!n || !repeats) return 2;
 long *a=calloc((size_t)n,sizeof(long));
 long *b=calloc((size_t)n,sizeof(long));
 long *c=calloc((size_t)n,sizeof(long));
 if(!a || !b || !c) {{free(a);free(b);free(c);return 2;}}
 for(long i=0;i<n;i++) {{a[i]={initialization};b[i]=1;c[i]=1;}}
 {setup}
 uint64_t checksum=0;
 for(long iteration=0;iteration<repeats;iteration++) {{
  {reset}
  checksum+=(uint64_t){call};
 }}
 checksum+=(uint64_t)a[n-1]+(uint64_t)b[n-1]+(uint64_t){tail};
 printf("%llu\\n",(unsigned long long)checksum);
 free(a);free(b);free(c);
 return ferror(stdout)?2:0;
}}
"""
